@dataclass
class Candidate:
    path: str
    language: str
    text: str
    size: int
    infra: bool
    score: float = 0.0
    reasons: list[str] = field(default_factory=list)
    included: bool = False

    @property
    def line_count(self) -> int:
        return self.text.count("\n") + (0 if self.text.endswith("\n") else 1)


def language_for(path: str) -> str | None:
    name = posixpath.basename(path).lower()
    if name in LANG_BY_NAME:
        return LANG_BY_NAME[name]
    if name.startswith("dockerfile") or name.endswith(".dockerfile"):
        return "dockerfile"
    if name.startswith("docker-compose") and name.endswith((".yml", ".yaml")):
        return "yaml"
    return LANG_BY_EXT.get(posixpath.splitext(name)[1])


def is_readme(path: str) -> bool:
    return bool(README.match(posixpath.basename(path)))


def is_infra(path: str, text: str = "") -> bool:
    lower = path.lower()
    name = posixpath.basename(lower)
    ext = posixpath.splitext(name)[1]
    dirs = set(lower.split("/")[:-1])
    if name in INFRA_NAMES or name.startswith("dockerfile") or name.endswith(".dockerfile"):
        return True
    if name.startswith("docker-compose") and ext in (".yml", ".yaml"):
        return True
    if lower.startswith((".github/workflows/", ".circleci/")) or "/.github/workflows/" in lower:
        return True
    if ext in (".tf", ".hcl"):
        return True
    if ext in (".yml", ".yaml") and (dirs & INFRA_DIRS or ("apiVersion:" in text and "kind:" in text)):
        return True
    return False


def path_skip_reason(path: str, size: int) -> str | None:
    """Why a file is skipped based on its path and size alone (before reading it), or None."""
    parts = path.lower().split("/")
    name = parts[-1]
    if any(p in SKIP_DIRS or p.endswith(".egg-info") for p in parts[:-1]):
        return "vendored or build output"
    if SECRET_NAME.match(name):
        return "possible secret"
    if name in LOCKFILES:
        return "lockfile"
    if posixpath.splitext(name)[1] in BINARY_EXTS:
        return "binary, media or data"
    if GENERATED_NAME.search(name):
        return "generated or minified"
    if size > config.MAX_FILE_BYTES:
        return "over 200 KB"
    if size == 0:
        return "empty"
    if language_for(path) is None and not is_infra(path):
        return "not source code"
    return None


def decode(data: bytes) -> str | None:
    if b"\0" in data[:8192]:
        return None
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return None
    return text.lstrip("﻿").replace("\r\n", "\n")


def content_skip_reason(path: str, text: str | None) -> str | None:
    if text is None:
        return "binary or not UTF-8"
    if SECRET_CONTENT.search(text):
        return "possible secret"
    lines = text.split("\n")
    if GENERATED_MARK.search("\n".join(lines[:5])):
        return "generated or minified"
    if max(len(line) for line in lines) > 3000:
        return "generated or minified"
    if sum(1 for line in lines if line.strip()) < 3 and not is_infra(path):
        return "trivial"
    return None


# --- ranking ------------------------------------------------------------------------------

_IMPORT_LINE = re.compile(
    r"^\s*(?:from\s+\S+\s+import\b|import\b|export\b.*\bfrom\b|#\s*include\b|use\b|using\b|require\b"
    r"|\}\s*from\b|.*\brequire\s*\(|.*\bimport\s*\(|`include\b|mod\b|library\b)",
)
_WORDS = re.compile(r"[A-Za-z0-9_][A-Za-z0-9_-]*")
_HDL_INSTANCE = re.compile(r"^\s*([A-Za-z_]\w*)\s*(?:#\s*\(|[A-Za-z_]\w*\s*\()", re.M)


def _keys(c: Candidate) -> set[str]:
    """Names other files would use to import this one."""
    if c.language in HDL_LANGS:
        return {m.lower() for m in HDL_MODULE.findall(c.text)}
    stem = posixpath.splitext(posixpath.basename(c.path))[0].lower()
    if stem in GENERIC_STEMS:  # index.ts, __init__.py, mod.rs are imported by their folder name
        parent = posixpath.basename(posixpath.dirname(c.path)).lower()
        return {parent} if parent else set()
    return {stem} if len(stem) >= 2 else set()


def _import_words(c: Candidate) -> set[str]:
    words: set[str] = set()
    if c.language in HDL_LANGS:
        words |= {w.lower() for w in _HDL_INSTANCE.findall(c.text) if w not in HDL_KEYWORDS}
    if c.language in CONFIG_LANGS:
        return words
    in_go_block = False
    for line in c.text.split("\n")[:400]:
        if c.language == "go":
            if line.startswith("import ("):
                in_go_block = True
            elif in_go_block and line.startswith(")"):
                in_go_block = False
        if in_go_block or _IMPORT_LINE.match(line):
            for w in _WORDS.findall(line):
                w = w.lower()
                words.add(w)
                words.update(p for p in w.split("-") if p)
    return words


_JS_LANGS = {"javascript", "typescript", "tsx", "vue", "svelte"}
_JS_SPEC = re.compile(r"""(?:\bfrom|\bimport|\brequire\s*\(|\bimport\s*\()\s*['"]([^'"\n]+)['"]""")
_PY_FROM = re.compile(r"^[ \t]*from[ \t]+(\.*)([\w.]*)[ \t]+import[ \t]+\(?([\w ,\t]*)", re.M)
_PY_IMPORT = re.compile(r"^[ \t]*import[ \t]+([\w.]+(?:[ \t]*,[ \t]*[\w.]+)*)", re.M)


class _Index:
    """Lookups from import specifiers to repo files."""

    def __init__(self, cands: list[Candidate]):
        self.paths = {c.path for c in cands}
        self.js: dict[str, str] = {}  # path without extension, and folder of an index file -> path
        self.py: dict[str, list[str]] = defaultdict(list)  # every dotted suffix of a module -> paths
        self.words: dict[str, list[str]] = defaultdict(list)  # bare import name -> paths
        for c in cands:
            root = posixpath.splitext(c.path)[0]
            if c.language in _JS_LANGS or c.language in STYLE_LANGS:
                self.js.setdefault(root, c.path)
                if posixpath.basename(root) == "index":
                    self.js.setdefault(posixpath.dirname(root), c.path)
            elif c.language == "python":
                parts = (posixpath.dirname(c.path) if posixpath.basename(root) == "__init__" else root).split("/")
                for i in range(len(parts)):
                    self.py[".".join(parts[i:])].append(c.path)
            for k in _keys(c):
                self.words[k].append(c.path)


def _imports(c: Candidate, idx: _Index) -> dict[str, float]:
    """Repo files this one imports: weight 1, or 1/n when an import could mean n files.

    JS/TS and Python imports are resolved as paths; other languages match bare names."""
    out: dict[str, float] = {}

    def add(hits: list[str]) -> None:
        for h in hits:
            out[h] = max(out.get(h, 0.0), 1 / len(hits))

    if c.language in _JS_LANGS:
        base = posixpath.dirname(c.path)
        for spec in _JS_SPEC.findall(c.text):
            if spec.startswith("."):
                targets = [posixpath.normpath(posixpath.join(base, spec))]
            elif spec.startswith(("@/", "~/")):  # common alias for the source root
                targets = [p + spec[2:] for p in ("src/", "", "app/")]
            else:
                continue  # a package, not a file in this repo
            for t in targets:
                hit = t if t in idx.paths else idx.js.get(t) or idx.js.get(posixpath.splitext(t)[0])
                if hit:
                    add([hit])
                    break
        return out
    if c.language == "python":
        pkg = [p for p in posixpath.dirname(c.path).split("/") if p]
        for dots, mod, names in _PY_FROM.findall(c.text):
            base = (pkg[: len(pkg) - (len(dots) - 1)] if dots else []) + (mod.split(".") if mod else [])
            for m in [base] + [base + [n.split(" as ")[0].strip()] for n in names.split(",") if n.strip()]:
                if m and (hits := idx.py.get(".".join(m))):
                    add(hits)
        for group in _PY_IMPORT.findall(c.text):
            for m in group.split(","):
                if hits := idx.py.get(m.strip()):
                    add(hits)
        return out
    for w in _import_words(c):
        if hits := idx.words.get(w):
            add(hits)
    return out


def _is_barrel(c: Candidate) -> bool:
    """__init__.py / index.ts style files that mostly re-export other modules."""
    if c.language in CONFIG_LANGS:
        return False
    code = [line for line in c.text.split("\n") if line.strip() and not line.lstrip().startswith(("#", "//", "*", "/*"))]
    imports = sum(1 for line in code if _IMPORT_LINE.match(line) or line.lstrip().startswith("export *"))
    return imports >= 5 and imports > 0.4 * len(code)


def rank(cands: list[Candidate], readme: str = "") -> None:
    """Score candidates in place and mark the ones to include."""
    idx = _Index(cands)
    fan_in: dict[str, float] = defaultdict(float)
    for c in cands:
        for target, weight in _imports(c, idx).items():
            if target != c.path:
                fan_in[target] += weight
    readme_l = readme.lower()
    hdl_files = [c for c in cands if c.language in HDL_LANGS]

    for c in cands:
        lower = c.path.lower()
        name = posixpath.basename(lower)
        stem = posixpath.splitext(name)[0]
        dirs = lower.split("/")[:-1]
        score, reasons = 0.0, []

        if c.infra:
            score += 2
            reasons.append("deployment/CI")
        elif name in MANIFESTS:
            score += 1.5
            reasons.append("dependency manifest")
        elif c.language in CONFIG_LANGS:
            score -= 1
        elif c.language in STYLE_LANGS:
            score -= 1.5
        else:
            score += 1

        if stem in ENTRY_STEMS and not c.infra and c.language not in CONFIG_LANGS and (
            len(dirs) <= 2 or "cmd" in dirs
        ):
            score += 3
            reasons.append("entry point")

        barrel = _is_barrel(c)
        n = 0 if barrel else round(fan_in[c.path])  # a barrel's importers really want what it re-exports
        if c.language in HDL_LANGS and len(hdl_files) > 1 and _keys(c):
            if n == 0:
                score += 2
                reasons.append("top-level module")
        if n:
            # Tiny files and test helpers get imported a lot without being much to talk about.
            damp = (0.3 if TEST_PATH.search(lower) else 1.0) * (0.5 + 0.5 * min(1.0, c.line_count / 80))
            score += 2 * math.log2(1 + n) * damp
            reasons.append(f"imported by {n} file{'s' if n != 1 else ''}")

        if readme_l and (name in readme_l or lower in readme_l):
            score += 2
            reasons.append("mentioned in README")

        if barrel:
            score -= 1
        if set(dirs) & CORE_DIRS:
            score += 0.5
        lines = c.line_count
        if 30 <= lines <= 1500:
            score += 1
        elif lines < 10:
            score -= 1.5
        if TEST_PATH.search(lower):
            score -= 2
            reasons.append("test")
        if set(dirs) & LOW_DIRS:
            score -= 1.5
        score -= 0.3 * max(0, len(dirs) - 2)

        c.score, c.reasons = round(score, 2), reasons

    by_score = sorted(cands, key=lambda c: (-c.score, c.path))
    infra = [c for c in by_score if c.infra][: config.MAX_INFRA_FILES]
    rest = [c for c in by_score if not c.infra][: config.MAX_FILES - len(infra)]
    for c in infra + rest:
        c.included = True
