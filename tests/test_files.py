import pytest

from viva import config
from viva.files import Candidate, content_skip_reason, decode, is_infra, language_for, path_skip_reason, rank


@pytest.mark.parametrize(
    "path, reason",
    [
        (".env", "possible secret"),
        ("config/.env.production", "possible secret"),
        ("deploy/server.pem", "possible secret"),
        ("home/.ssh/id_rsa", "possible secret"),
        ("gcp/service-account-prod.json", "possible secret"),
        ("infra/prod.tfvars", "possible secret"),
        ("package-lock.json", "lockfile"),
        ("go.sum", "lockfile"),
        ("frontend/node_modules/react/index.js", "vendored or build output"),
        ("vendor/github.com/x/y.go", "vendored or build output"),
        ("dist/app.js", "vendored or build output"),
        ("assets/logo.png", "binary, media or data"),
        ("data/train.csv", "binary, media or data"),
        ("static/app.min.js", "generated or minified"),
        ("api/user_pb2.py", "generated or minified"),
        ("README.md", "not source code"),
        ("LICENSE", "not source code"),
        ("src/app.py", None),
        ("Dockerfile", None),
        ("docker-compose.yml", None),
        (".github/workflows/ci.yml", None),
        ("rtl/alu.sv", None),
        ("package.json", None),
    ],
)
def test_path_skip_reason(path, reason):
    assert path_skip_reason(path, 1000) == reason


def test_size_cap():
    assert path_skip_reason("src/big.py", config.MAX_FILE_BYTES + 1) == "over 200 KB"


def test_content_skip_reason():
    assert content_skip_reason("a.py", None) == "binary or not UTF-8"
    key = "x = '''\n-----BEGIN RSA PRIVATE KEY-----\nabc\n'''\n"
    assert content_skip_reason("a.py", key) == "possible secret"
    assert content_skip_reason("a.py", "AWS = 'AKIAABCDEFGHIJKLMNOP'\nb = 1\nc = 2\n") == "possible secret"
    assert content_skip_reason("gen.go", "// Code generated by protoc. DO NOT EDIT.\npackage x\nvar a = 1\n") == "generated or minified"
    assert content_skip_reason("a.py", "import os\n\ndef f():\n    return os.getcwd()\n") is None
    assert decode(b"\x00\x01binary") is None


def test_infra_detection():
    assert is_infra("k8s/deployment.yaml")
    assert is_infra("whatever.yaml", "apiVersion: apps/v1\nkind: Deployment\n")
    assert is_infra("terraform/main.tf")
    assert not is_infra("config/settings.yaml", "debug: true\n")


def test_language_for():
    assert language_for("src/App.tsx") == "tsx"
    assert language_for("rtl/top.v") == "verilog"
    assert language_for("Dockerfile.prod") == "dockerfile"
    assert language_for("notes.md") is None


def cand(path, text, infra=False):
    return Candidate(path=path, language=language_for(path) or "text", text=text, size=len(text), infra=infra)


def test_rank_prefers_entry_points_and_imported_files():
    body = "\n".join(f"x{i} = {i}" for i in range(40))
    files = [
        cand("app/main.py", "from app.store import Store\nfrom app.utils import fmt\n" + body),
        cand("app/store.py", "class Store:\n    pass\n" + body),
        cand("app/api.py", "from app.store import Store\n" + body),
        cand("app/utils.py", body),
        cand("tests/test_store.py", "from app.store import Store\n" + body),
        cand("Dockerfile", "FROM python:3.12\nCOPY . .\nCMD python -m app\n", infra=True),
    ]
    rank(files, readme="Run `python app/main.py`.")
    by = {f.path: f for f in files}
    assert "entry point" in by["app/main.py"].reasons
    assert "mentioned in README" in by["app/main.py"].reasons
    assert "imported by 3 files" in by["app/store.py"].reasons
    assert by["app/store.py"].score > by["app/utils.py"].score > by["tests/test_store.py"].score
    assert all(f.included for f in files)


def test_rank_caps_and_reserves_infra(monkeypatch):
    monkeypatch.setattr(config, "MAX_FILES", 5)
    monkeypatch.setattr(config, "MAX_INFRA_FILES", 2)
    files = [cand(f"src/m{i}.py", "a = 1\nb = 2\nc = 3\n" * 20) for i in range(10)]
    files += [cand(f".github/workflows/w{i}.yml", "on: push\njobs: {}\n", infra=True) for i in range(3)]
    rank(files)
    included = [f for f in files if f.included]
    assert len(included) == 5
    assert sum(f.infra for f in included) == 2


def test_verilog_top_module_and_instances():
    alu = cand("rtl/alu.v", "module alu(input a, output y);\n  assign y = a;\nendmodule\n")
    top = cand("rtl/top.v", "module top(input clk);\n  alu u_alu (.a(clk), .y());\n  alu u_alu2 (.a(clk), .y());\nendmodule\n")
    rank([alu, top])
    assert "imported by 1 file" in alu.reasons
    assert "top-level module" in top.reasons


def test_js_imports_resolve_paths_not_package_names():
    common = cand("packages/ui/src/common.ts", "export const a = 1;\nexport const b = 2;\nexport const c = 3;\n" * 5)
    button = cand("packages/ui/src/components/Button.tsx", 'import { a } from "../common";\nexport const Button = () => a;\n' * 3)
    store = cand("packages/ui/src/store/index.ts", "export const store = {};\nexport const x = 1;\nexport const y = 2;\n" * 5)
    other = cand(
        "packages/app/src/main.ts",
        'import { a } from "@scope/common";\nimport { store } from "../../ui/src/store";\nimport "./styles.css";\n' * 2,
    )
    rank([common, button, store, other])
    assert "imported by 1 file" in common.reasons  # Button's relative import, not the @scope/common package
    assert "imported by 1 file" in store.reasons  # folder import resolves to index.ts


def test_python_relative_and_absolute_imports():
    body = "\n".join(f"v{i} = {i}" for i in range(40))
    core = cand("src/pkg/core.py", "class Core:\n    pass\n" + body)
    util = cand("src/pkg/util.py", body)
    init = cand(
        "src/pkg/__init__.py",
        "from .core import Core as Core\nfrom .util import v1 as v1\nfrom .util import v2 as v2\n"
        "from .util import v3 as v3\nfrom .util import v4 as v4\n",
    )
    cli = cand("src/pkg/cli.py", "from pkg.core import Core\nfrom . import util\n" + body)
    users = [cand(f"tests/test_{i}.py", "import pkg\n" + body) for i in range(5)]
    rank([core, util, init, cli, *users])
    assert "imported by 2 files" in core.reasons  # __init__ (relative) + cli (absolute)
    assert "imported by 2 files" in util.reasons  # __init__ + cli's `from . import util`
    assert not any(r.startswith("imported by") for r in init.reasons)  # barrel gets no credit
    assert core.score > init.score
